export function displayLabel(value: string | number | boolean | null | undefined, context: LabelContext = 'general'): string {
  if (value === null || value === undefined || value === '' || value === 'null' || value === 'undefined') return '—';
  if (typeof value === 'boolean') return value ? 'Sí' : 'No';
  const text = String(value);
  const contextual = CONTEXT_LABELS[context];
  if (contextual && Object.hasOwn(contextual, text)) return contextual[text];
  if (Object.hasOwn(DISPLAY_LABELS, text)) return DISPLAY_LABELS[text];
  return /^[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+$/.test(text) ? 'Etiqueta pendiente de definición' : text;
}
